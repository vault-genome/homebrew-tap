# Writes Formula/vaultgenome.rb for a release of vaultgenome-core from the
# release's own signed list of hashes: downloads checksums-<tag>.txt with
# its Sigstore bundle, verifies the list under the release workflow's
# identity, and takes the six tools' SHA-256 from it — nothing is hashed
# here, nothing is typed by hand.
#
# Usage: bin/update-formula.sh vX.Y.Z        (needs gh, cosign)
set -euo pipefail
TAG="${1:?usage: update-formula.sh vX.Y.Z}"
REPO="vault-genome/vaultgenome-core"
HERE="$(cd "$(dirname "$0")/.." && pwd)"
WORK="$(mktemp -d)"; trap 'rm -rf "$WORK"' EXIT
gh release download "$TAG" --repo "$REPO" --dir "$WORK" \
  --pattern "checksums-$TAG.txt" --pattern "checksums-$TAG.txt.sigstore.json" >/dev/null
cosign verify-blob --new-bundle-format --bundle "$WORK/checksums-$TAG.txt.sigstore.json" \
  --certificate-identity "https://github.com/$REPO/.github/workflows/release.yml@refs/tags/$TAG" \
  --certificate-oidc-issuer https://token.actions.githubusercontent.com \
  "$WORK/checksums-$TAG.txt" >/dev/null 2>&1 || { echo "the checksums list of $TAG did not verify under the release workflow's identity"; exit 1; }
sha() { awk -v f="$1" '$2 == f { print $1 }' "$WORK/checksums-$TAG.txt" | grep -E '^[0-9a-f]{64}$' || { echo "no hash for $1 in checksums-$TAG.txt" >&2; exit 1; }; }
VERSION="${TAG#v}"
BASE="https://github.com/$REPO/releases/download/$TAG"
# Homebrew reads the version from the URL: vX.Y.Z it reads right, and names
# it redundant if the formula repeats it; a pre-release tag (vX.Y.Z-rcN) it
# reads wrong — the trailing digits of the platform, arm64 → 64 — so the
# formula names it then.
VERSION_LINE=""
case "$VERSION" in *-*) VERSION_LINE="  version \"$VERSION\"
";; esac
cat > "$HERE/Formula/vaultgenome.rb" <<EOF
# Generated by bin/update-formula.sh $TAG from the release's signed
# checksums-$TAG.txt; do not edit the hashes by hand.
class Vaultgenome < Formula
  desc "Attested key release for fine-tuned models: the acpctl and acp-keygen tools"
  homepage "https://github.com/$REPO"
${VERSION_LINE}  license "AGPL-3.0-or-later"

  on_macos do
    on_arm do
      url "$BASE/acpctl-darwin-arm64"
      sha256 "$(sha acpctl-darwin-arm64)"
      resource "acp-keygen" do
        url "$BASE/acp-keygen-darwin-arm64"
        sha256 "$(sha acp-keygen-darwin-arm64)"
      end
    end
    on_intel do
      url "$BASE/acpctl-darwin-amd64"
      sha256 "$(sha acpctl-darwin-amd64)"
      resource "acp-keygen" do
        url "$BASE/acp-keygen-darwin-amd64"
        sha256 "$(sha acp-keygen-darwin-amd64)"
      end
    end
  end

  on_linux do
    on_arm do
      url "$BASE/acpctl-linux-arm64"
      sha256 "$(sha acpctl-linux-arm64)"
      resource "acp-keygen" do
        url "$BASE/acp-keygen-linux-arm64"
        sha256 "$(sha acp-keygen-linux-arm64)"
      end
    end
    on_intel do
      url "$BASE/acpctl"
      sha256 "$(sha acpctl)"
      resource "acp-keygen" do
        url "$BASE/acp-keygen"
        sha256 "$(sha acp-keygen)"
      end
    end
  end

  def install
    # The download is the binary itself, named by platform in the release
    # (the Linux x86-64 one by its bare name); it is installed under its name.
    suffix = if OS.mac?
      Hardware::CPU.arm? ? "-darwin-arm64" : "-darwin-amd64"
    else
      Hardware::CPU.arm? ? "-linux-arm64" : ""
    end
    bin.install "acpctl#{suffix}" => "acpctl"
    resource("acp-keygen").stage { bin.install "acp-keygen#{suffix}" => "acp-keygen" }
  end

  test do
    assert_match "acpctl $TAG", shell_output("#{bin}/acpctl version")
    assert_predicate bin/"acp-keygen", :executable?
  end
end
EOF
echo "Formula/vaultgenome.rb written for $TAG ($VERSION) from the verified checksums-$TAG.txt"
